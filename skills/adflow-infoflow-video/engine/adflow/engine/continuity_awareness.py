# -*- coding: utf-8 -*-
"""
分镜连续性感知 — 按镜头数和风格分级注入连续性约束

不是硬账本，是软提醒。根据实际场景自动判断是否需要、需要多少：
  - ≤2 镜（口播/单场景）→ 跳过，不浪费 prompt token
  - 混剪/快切/直播切片 → 只提醒产品一致性
  - 叙事类 3-6 镜 → 完整连续性提醒
"""


class ContinuityAwareness:
    """分镜连续性感知 — 分级提醒而非硬约束"""

    # 不需要连续性的风格（节奏优先，场景跳跃是故意的）
    SKIP_STYLES = frozenset({"快节奏卡点", "快切", "混剪", "直播切片", "卡点"})

    @staticmethod
    def build_context(shot_count: int, pace_style: str = "") -> str:
        """根据镜头数和风格，返回不同强度的连续性约束文本

        Args:
            shot_count: 实际镜头数
            pace_style: 节奏风格（如"快节奏卡点"/"中速叙事"/"慢节奏情感"）

        Returns:
            注入 prompt 的文本，不需要时返回空字符串
        """
        if shot_count <= 2:
            # 口播/单场景：不需要连续性约束
            return ""

        if pace_style and any(s in pace_style for s in ContinuityAwareness.SKIP_STYLES):
            # 混剪/快切：节奏优先，只提醒产品一致性
            return (
                "## 混剪节奏（场景跳跃是故意的，注意产品一致性即可）\n"
                "- 产品包装/外观在不同镜头中保持一致\n"
                "- BGM 风格贯穿始终\n"
                "- 字幕样式统一\n"
            )

        # 叙事类（测评/品牌故事/种草）：有逻辑关联的 3-6 镜
        return (
            "## 分镜连续性提醒（自然衔接即可，优先保证文案质量）\n\n"
            "1. **场景过渡**：如果要换场景，给一个简短的动作承接\n"
            '   例如"下班回到家打开冰箱"而不是上镜办公室下镜厨房\n\n'
            "2. **产品状态递进**：未拆封→打开→正在吃/用→用完的效果\n"
            "   避免上一镜产品完整包装、下一镜已经在吃\n\n"
            "3. **情绪曲线递进**：不要每一镜都是同样的情绪强度\n"
            "   例如 好奇→共鸣→惊喜→冲动→行动\n\n"
            "4. **如果素材不够，优先保证文案质量**，连续性只是加分项\n"
        )
